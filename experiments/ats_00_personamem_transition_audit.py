"""
ATS data audit 00b — PersonaMem-v2 RAW preference transitions
===============================================================

Why this exists
---------------
The released benchmark CSV's `updated=True` rows are dominated by / may be
restricted to `ask_to_forget` evaluation items. Genuine synthetic preference
flips generated by PersonaMem-v2 live in the raw persona JSON files via:

    preference_updates: {old_preference: new_preference}

and corresponding conversation blocks with:

    updated=True, prev_pref=old_preference, preference=new_preference

So this audit uses benchmark CSVs ONLY to recover split/persona/raw-file
membership, and uses RAW persona JSON as the source of truth for native
preference transitions.

This is an audit only. It does not train ATS.

Dependencies
------------
    pip install pandas numpy huggingface_hub

Run from the perspective-llm repository root in Spyder.
"""

# %% Imports
from __future__ import annotations

import json
import math
import re
from pathlib import Path
from typing import Any, Dict, List, Tuple

import numpy as np
import pandas as pd


# %% USER CONFIG
HF_REPO = "bowen-upenn/PersonaMem-v2"
DATA_ROOT = Path("data/personamem_v2")
RESULT_ROOT = Path("results/ats_transition_audit_raw")

# Small first pass. Set to None later to audit every persona in a split.
RAW_PERSONAS_PER_SPLIT = 20
RANDOM_SEED = 17

SPLIT_FILES = {
    "train": "benchmark/text/train.csv",
    "val": "benchmark/text/val.csv",
    "test": "benchmark/text/benchmark.csv",
}


# %% Helpers
def ensure_dirs():
    DATA_ROOT.mkdir(parents=True, exist_ok=True)
    RESULT_ROOT.mkdir(parents=True, exist_ok=True)


def _hf_download(filename: str) -> Path:
    from huggingface_hub import hf_hub_download

    p = hf_hub_download(
        repo_id=HF_REPO,
        repo_type="dataset",
        filename=filename,
        local_dir=str(DATA_ROOT),
    )
    return Path(p)


def local_or_download(relpath: str) -> Path:
    local = DATA_ROOT / relpath
    if local.exists():
        return local
    return _hf_download(relpath)


def norm(x: Any) -> str:
    if x is None:
        return ""
    if isinstance(x, float) and math.isnan(x):
        return ""
    return str(x).strip()


def as_bool(x: Any) -> bool:
    if isinstance(x, bool):
        return x
    return norm(x).lower() in {"true", "1", "yes", "y"}


def normalize_repo_path(x: Any, default_dir: str = "data/raw_data") -> str:
    s = norm(x).replace("\\", "/")
    if not s:
        return ""

    # Keep from data/... onward if present.
    if "data/" in s:
        s = s[s.index("data/") :]
    elif "/" not in s:
        s = f"{default_dir}/{s}"
    elif not s.startswith("data/"):
        # Handle raw_data/foo.json etc.
        if s.startswith("raw_data/"):
            s = "data/" + s

    return s.lstrip("./")


def extract_persona_payload(raw_obj: Dict[str, Any], persona_id: Any) -> Dict[str, Any]:
    pid = norm(persona_id)
    if pid in raw_obj:
        return raw_obj[pid]

    for k, v in raw_obj.items():
        if norm(k) == pid:
            return v

    if len(raw_obj) == 1:
        return next(iter(raw_obj.values()))

    raise KeyError(f"persona_id={persona_id!r} not found in raw JSON")


def iter_blocks(persona: Dict[str, Any]):
    conversations = persona.get("conversations", {})
    if not isinstance(conversations, dict):
        return
    for scenario, blocks in conversations.items():
        if not isinstance(blocks, list):
            continue
        for idx, block in enumerate(blocks):
            if isinstance(block, dict):
                yield scenario, idx, block


# %% Load benchmark CSVs (for split membership only)
def load_splits() -> Dict[str, pd.DataFrame]:
    out = {}
    for split, rel in SPLIT_FILES.items():
        path = local_or_download(rel)
        df = pd.read_csv(path)
        df["split"] = split
        out[split] = df
    return out


def print_csv_updated_diagnostic(splits: Dict[str, pd.DataFrame]):
    print("\n[diagnostic: what does updated=True mean in released benchmark CSVs?]")
    rows = []
    for split, df in splits.items():
        upd = df[df["updated"].map(as_bool)].copy()
        vc = upd["pref_type"].fillna("<NA>").astype(str).value_counts()
        rows.append({
            "split": split,
            "rows": len(df),
            "personas": df["persona_id"].nunique(),
            "updated_rows": len(upd),
            "updated_pref_types": dict(vc),
        })
    for r in rows:
        print(r)


# %% Split overlap audit
def split_overlap_table(splits: Dict[str, pd.DataFrame]) -> pd.DataFrame:
    sets = {k: set(v["persona_id"].astype(str).unique()) for k, v in splits.items()}
    names = list(sets)
    out = []
    for i, a in enumerate(names):
        for b in names[i + 1 :]:
            ov = sets[a] & sets[b]
            out.append({
                "split_a": a,
                "split_b": b,
                "n_overlap": len(ov),
                "example_ids": ",".join(sorted(ov)[:10]),
            })
    return pd.DataFrame(out)


# %% Persona/raw-file selection
def persona_file_table(df: pd.DataFrame) -> pd.DataFrame:
    cols = ["persona_id", "raw_persona_file"]
    x = df[cols].dropna().drop_duplicates().copy()
    x["raw_persona_file"] = x["raw_persona_file"].map(normalize_repo_path)
    x = x[x["raw_persona_file"] != ""]
    return x


def sample_persona_files(df: pd.DataFrame, n: int | None, seed: int) -> pd.DataFrame:
    x = persona_file_table(df)
    # One raw file per persona for audit.
    x = x.drop_duplicates(subset=["persona_id"])
    if n is None or len(x) <= n:
        return x
    return x.sample(n=n, random_state=seed)


# %% Raw transition extraction
def extract_raw_transitions(persona_id: Any, raw_relpath: str) -> Tuple[List[Dict[str, Any]], Dict[str, Any]]:
    path = local_or_download(raw_relpath)
    with open(path, "r", encoding="utf-8") as f:
        raw_obj = json.load(f)

    persona = extract_persona_payload(raw_obj, persona_id)
    pref_updates = persona.get("preference_updates", {})
    if not isinstance(pref_updates, dict):
        pref_updates = {}

    # Index dataset-native updated conversation blocks.
    blocks = []
    for scenario, idx, block in iter_blocks(persona):
        if not as_bool(block.get("updated", False)):
            continue

        pref_type = norm(block.get("pref_type", ""))
        pref = norm(block.get("preference", ""))
        prev = norm(block.get("prev_pref", ""))

        # Explicit forget requests are a different operation, not a preference flip.
        if pref_type == "ask_to_forget" or pref.startswith("Do not remember '"):
            continue

        if not prev or not pref:
            continue

        blocks.append({
            "persona_id": persona_id,
            "raw_persona_file": raw_relpath,
            "scenario": scenario,
            "block_index_within_scenario": idx,
            "pref_type": pref_type,
            "who": norm(block.get("who", "")),
            "old_preference": prev,
            "new_preference": pref,
            "pair_in_preference_updates_map": pref_updates.get(prev) == pref,
            "n_messages": len(block.get("conversations", [])) if isinstance(block.get("conversations"), list) else np.nan,
        })

    meta = {
        "persona_id": persona_id,
        "raw_persona_file": raw_relpath,
        "n_preference_updates_map": len(pref_updates),
        "n_nonforget_updated_blocks": len(blocks),
        "n_crosschecked_pairs": sum(bool(b["pair_in_preference_updates_map"]) for b in blocks),
    }
    return blocks, meta


# %% Main
def main():
    ensure_dirs()
    print("=" * 78)
    print("ATS / PersonaMem-v2 RAW transition audit")
    print("=" * 78)

    splits = load_splits()

    # First: explain the confusing result from audit 00.
    print_csv_updated_diagnostic(splits)

    # Always check split overlap; audit 00 returned too early before doing this.
    overlap = split_overlap_table(splits)
    print("\n[persona-id overlap across released CSV splits]")
    print(overlap.to_string(index=False))
    overlap.to_csv(RESULT_ROOT / "persona_split_overlap.csv", index=False)

    all_transitions = []
    all_meta = []

    for split_i, (split, df) in enumerate(splits.items()):
        selected = sample_persona_files(
            df,
            n=RAW_PERSONAS_PER_SPLIT,
            seed=RANDOM_SEED + split_i,
        )
        print(f"\n[raw audit: {split}] personas={len(selected)}")

        for j, (_, row) in enumerate(selected.iterrows(), 1):
            pid = row["persona_id"]
            raw_rel = row["raw_persona_file"]
            print(f"  {j:>3}/{len(selected)} persona={pid}  {Path(raw_rel).name}")
            try:
                transitions, meta = extract_raw_transitions(pid, raw_rel)
                for t in transitions:
                    t["split"] = split
                meta["split"] = split
                all_transitions.extend(transitions)
                all_meta.append(meta)
            except Exception as exc:
                all_meta.append({
                    "split": split,
                    "persona_id": pid,
                    "raw_persona_file": raw_rel,
                    "error": repr(exc),
                })

    trans_df = pd.DataFrame(all_transitions)
    meta_df = pd.DataFrame(all_meta)

    trans_df.to_csv(RESULT_ROOT / "raw_preference_transitions.csv", index=False)
    meta_df.to_csv(RESULT_ROOT / "raw_persona_transition_summary.csv", index=False)

    if len(meta_df):
        summary = (
            meta_df.groupby("split", dropna=False)
            .agg(
                personas_audited=("persona_id", "size"),
                preference_updates_in_map=("n_preference_updates_map", "sum"),
                nonforget_updated_blocks=("n_nonforget_updated_blocks", "sum"),
                crosschecked_pairs=("n_crosschecked_pairs", "sum"),
            )
            .reset_index()
        )
    else:
        summary = pd.DataFrame()

    print("\n[RAW transition summary]")
    if len(summary):
        print(summary.to_string(index=False))
        summary.to_csv(RESULT_ROOT / "raw_transition_counts_by_split.csv", index=False)
    else:
        print("No raw personas were successfully audited.")

    print("\n[examples]")
    if len(trans_df):
        cols = [
            "split", "persona_id", "pref_type",
            "old_preference", "new_preference",
            "pair_in_preference_updates_map",
        ]
        print(trans_df[cols].head(12).to_string(index=False))
    else:
        print("No non-forget raw preference transitions found.")

    verdict = {
        "benchmark_csv_updated_rows_are_not_safe_proxy_for_preference_flips": True,
        "raw_persona_files_contain_preference_updates": bool(
            len(meta_df)
            and meta_df.get("n_preference_updates_map", pd.Series(dtype=float)).fillna(0).sum() > 0
        ),
        "raw_updated_blocks_crosscheck_preference_updates": bool(
            len(meta_df)
            and meta_df.get("n_crosschecked_pairs", pd.Series(dtype=float)).fillna(0).sum() > 0
        ),
        "note": (
            "Use raw persona preference_updates / updated conversation blocks as "
            "dataset-native controlled transition ground truth. Use benchmark CSV "
            "QA rows for downstream personalization evaluation, not as the sole "
            "source of transition labels."
        ),
    }

    with open(RESULT_ROOT / "audit_verdict.json", "w", encoding="utf-8") as f:
        json.dump(verdict, f, indent=2, ensure_ascii=False)

    print("\n[verdict]")
    print(json.dumps(verdict, indent=2, ensure_ascii=False))
    print("\nWrote:", RESULT_ROOT.resolve())


if __name__ == "__main__":
    main()
